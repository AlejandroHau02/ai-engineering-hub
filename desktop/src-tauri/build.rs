use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    // Only these commands are part of the app manifest; the capability grants
    // exactly their generated `allow-*` permissions.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "run_doctor",
            "preview_sync",
            "discard_plan",
            "apply_sync",
            "recover_transaction",
            "read_catalog",
        ]),
    ))
    .expect("failed to run tauri-build");

    // Static imports of the executable resolve from System32 only, so a DLL
    // planted next to an unzipped portable copy is never loaded
    // (LOAD_LIBRARY_SEARCH_SYSTEM32 = 0x800).
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg-bins=/DEPENDENTLOADFLAG:0x800");
    }

    embed_integrity_table();
}

/// Trust anchor: SHA-256 of every bundled runtime/core file, compiled into the
/// executable. A manifest next to the runtime can be rewritten by whoever can
/// write the runtime; this table cannot without rebuilding the app.
fn embed_integrity_table() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let resources = manifest_dir.join("resources");
    println!("cargo:rerun-if-changed=resources");
    let mut files = Vec::new();
    for tree in ["python", "syncode"] {
        let root = resources.join(tree);
        println!("cargo:rerun-if-changed=resources/{tree}");
        if root.is_dir() {
            collect(&resources, &root, &mut files);
        }
    }
    files.sort();
    let mut out = String::from(
        "/// Generated by build.rs: (path relative to the resource dir, SHA-256).\n\
         pub const BUNDLE_FILES: &[(&str, &str)] = &[\n",
    );
    for (rel, digest) in &files {
        writeln!(out, "    ({rel:?}, {digest:?}),").unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("integrity_table.rs");
    std::fs::write(dest, out).expect("write integrity table");
}

fn collect(resources: &Path, dir: &Path, files: &mut Vec<(String, String)>) {
    for entry in std::fs::read_dir(dir).expect("read resources") {
        let entry = entry.expect("read resources entry");
        let path = entry.path();
        let kind = entry.file_type().expect("file type");
        assert!(
            !kind.is_symlink(),
            "symlink in bundled resources: {}",
            path.display()
        );
        if kind.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            collect(resources, &path, files);
        } else {
            let rel = path
                .strip_prefix(resources)
                .unwrap()
                .components()
                .map(|c| c.as_os_str().to_str().expect("non-UTF-8 resource path"))
                .collect::<Vec<_>>()
                .join("/");
            let digest = Sha256::digest(std::fs::read(&path).expect("read resource"));
            let hex = digest.iter().fold(String::new(), |mut s, b| {
                let _ = write!(s, "{b:02x}");
                s
            });
            files.push((rel, hex));
        }
    }
}
